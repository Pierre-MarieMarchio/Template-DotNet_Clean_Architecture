    private static int SelfTest()
    {
        var failures = new List<string>();
        var results = new List<string>();

        IEnumerable<Fixture> markdown =
        [
            .. MarkdownOffenders.Select((line, index) => new Fixture($"narration #{index + 1}", "NOTES.md", line, 1)),
            .. MarkdownInnocents.Select((line, index) => new Fixture($"look-alike #{index + 1}", "NOTES.md", line, 0)),
        ];

        foreach (var fixture in Fixtures.Concat(markdown))
        {
            var found = ScanFile(fixture.Path, fixture.Text).Findings;
            var verdict = fixture.Findings > 0 ? "fires " : "silent";

            if (found.Count == fixture.Findings)
            {
                results.Add($"  ok    {verdict}  {fixture.Label}  ({fixture.Path})");
            }
            else
            {
                failures.Add(
                    $"{fixture.Label} ({fixture.Path}): expected {fixture.Findings} finding(s), found {found.Count}"
                    + string.Concat(found.Select(finding => $"\n      line {finding.Line}: {finding.Rule}")));
            }
        }

        var spanned = MarkdownFindings(MarkerSpansItsParagraph);
        var lines = spanned.Findings.Select(finding => finding.Line).ToList();

        if (spanned.Exemptions != 1 || lines is not [5])
        {
            failures.Add(
                $"a narrative-ok marker should excuse its paragraph and stop at the blank line: honoured "
                + $"{spanned.Exemptions}, offenders on [{string.Join(", ", lines)}], expected 1 and [5]");
        }
        else
        {
            results.Add("  ok    fires   a narrative-ok marker excuses its paragraph and stops at the blank line");
        }

        var offenders = Fixtures.Count(fixture => fixture.Findings > 0) + MarkdownOffenders.Length;
        var innocents = Fixtures.Count(fixture => fixture.Findings == 0) + MarkdownInnocents.Length;

        Console.WriteLine($"Self-test: {offenders} offender(s), {innocents} innocent(s), 1 marker paragraph.");
        Console.WriteLine();

        foreach (var result in results)
        {
            Console.WriteLine(result);
        }

        Console.WriteLine();

        if (failures.Count > 0)
        {
            Console.WriteLine($"SELF-TEST FAILURES ({failures.Count}):");

            foreach (var failure in failures)
            {
                Console.WriteLine($"  ! {failure}");
            }

            return 1;
        }

        Console.WriteLine("The gate fires on every offender and on none of the innocents.");
        return 0;
    }

    private static string FirstLine(string text)
    {
        var end = text.IndexOf('\n', StringComparison.Ordinal);

        return (end < 0 ? text : text[..end]).TrimEnd('\r');
    }

    private static List<string> SplitLines(string text)
    {
        var lines = new List<string>();
        var start = 0;

        for (var index = 0; index < text.Length; index++)
        {
            var current = text[index];

            if (!IsLineBoundary(current))
            {
                continue;
            }

            lines.Add(text[start..index]);

            if (current == '\r' && index + 1 < text.Length && text[index + 1] == '\n')
            {
                index++;
            }

            start = index + 1;
        }

        if (start < text.Length)
        {
            lines.Add(text[start..]);
        }

        return lines;
    }

    private static bool IsLineBoundary(char character) => character is '\n'
        or '\r'
        or '\v'
        or '\f'
        or '\u001c'
        or '\u001d'
        or '\u001e'
        or '\u0085'
        or '\u2028'
        or '\u2029';

    private static string Truncate(string value, int limit) =>
        value.Length <= limit ? value : value[..limit];

    private static string Resolve(string path) => Path.TrimEndingDirectorySeparator(Path.GetFullPath(path));

    private static string Relative(string root, string path) =>
        Path.GetRelativePath(root, path).Replace(Path.DirectorySeparatorChar, '/');

    private static string ReadText(string path) => File.ReadAllText(path, new UTF8Encoding(false));
