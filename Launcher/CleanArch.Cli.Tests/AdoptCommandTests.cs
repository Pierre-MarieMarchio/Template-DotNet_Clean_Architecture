using System.Text.Json.Nodes;
using CleanArch.Cli.Adopt;
using CleanArch.Tooling.Projects;
using Shouldly;
using Xunit;

namespace CleanArch.Cli.Tests;

public sealed class AdoptCommandTests : IDisposable
{
    private const string _overview = """
        # Overview

        ## How this project was generated

        This project was generated by version 1.4.0 of `CleanArch.WebApi.Templates`, the
        `dotnet new` package that also holds `cleanarch-webapp` and `cleanarch-webpackage`.
        """;

    private readonly string _root = Directory.CreateTempSubdirectory("cleanarch-adopt-").FullName;
    private readonly FakeProcesses _processes = new();
    private readonly StringWriter _output = new();
    private readonly StringWriter _error = new();

    public void Dispose()
    {
        _output.Dispose();
        _error.Dispose();
        Directory.Delete(_root, recursive: true);
    }

    [Fact]
    public void Adopt_InfersTheProjectFileThisRepositoryCommits_FromItsTree()
    {
        ProjectFacts repository = GeneratedProject.At(Repository.Root).ShouldNotBeNull();

        JsonObject inferred = WithoutTheShapesOnlyTheTemplateHolds(AdoptCommand.JsonOf(repository, GeneratedProjectFacts.Provenance(repository.Root).ShouldNotBeNull()));
        JsonObject committed = WithoutTheShapesOnlyTheTemplateHolds(File.ReadAllText(Path.Combine(Repository.Root, ProjectLocator.FileName)));

        inferred.ToJsonString().ShouldBe(committed.ToJsonString());
    }

    [Fact]
    public void Adopt_WritesTheProjectFile_TheToolThenReads()
    {
        AProjectBeforeTheTool();

        Run(["adopt"], Path.Combine(_root, "Src")).ShouldBe(CleanArchCommand.Succeeded);

        ProjectFile file = ProjectLocator.Find(_root).ShouldNotBeNull().File;
        file.Template.ShouldBe(new TemplateReference("CleanArch.WebApi.Templates", "1.4.0"));
        file.Name.ShouldBe("Acme.Shop");
        file.Options.ShouldBe(new ProjectOptions("local", "postgresql", "none", Files: false, Ci: true, Sonar: true, AgentFiles: false, Aspire: false));
        file.Client.ShouldBeFalse();
        file.Web.ShouldNotBeNull().Scope.ShouldBe("acme-shop");
        file.Web.Apps.ShouldBe([new WebApp("Site", "vite-react", "public", "spa", 8081)]);
        file.Web.Packages.ShouldBe(["ui"]);
        file.Presentation.ShouldBe([new PresentationProject("Api", "api"), new PresentationProject("Worker", "worker")]);
        _output.ToString().ShouldStartWith($"Wrote {Path.Combine(_root, ProjectLocator.FileName)}:");
        _output.ToString().ShouldContain("\"version\": \"1.4.0\"");
        _error.ToString().ShouldBeEmpty();
    }

    [Fact]
    public void AdoptDryRun_PrintsTheFile_AndWritesNothing()
    {
        AProjectBeforeTheTool();

        Run(["adopt", "--dry-run"], _root).ShouldBe(CleanArchCommand.Succeeded);

        File.Exists(Path.Combine(_root, ProjectLocator.FileName)).ShouldBeFalse();
        _output.ToString().ShouldStartWith($"Would write {Path.Combine(_root, ProjectLocator.FileName)}:");
        _output.ToString().ShouldContain("\"name\": \"Acme.Shop\"");
    }

    [Fact]
    public void Adopt_AsksForTheVersion_WhenTheOverviewNoLongerSaysIt()
    {
        AProjectBeforeTheTool();
        File.Delete(Path.Combine(_root, "docs", "getting-started", "overview.md"));

        Run(["adopt"], _root).ShouldBe(CleanArchCommand.Failed);
        _error.ToString().ShouldContain("--template-version");
        File.Exists(Path.Combine(_root, ProjectLocator.FileName)).ShouldBeFalse();

        Run(["adopt", "--template-version", "1.1.0"], _root).ShouldBe(CleanArchCommand.Succeeded);
        ProjectLocator.Find(_root).ShouldNotBeNull().File.Template.ShouldBe(new TemplateReference(AdoptCommand.TemplatePackage, "1.1.0"));
    }

    [Fact]
    public void Adopt_WritesNothing_WhereAFactCannotBeReadFromTheFiles()
    {
        AProjectBeforeTheTool();
        Write("Src/Web/apps/Mystery/compose.yml", "WEB_MYSTERY_HOST_PORT:-8090}");

        Run(["adopt"], _root).ShouldBe(CleanArchCommand.Failed);

        _error.ToString().ShouldContain("Src/Web/apps/Mystery: its framework cannot be read from its files.");
        File.Exists(Path.Combine(_root, ProjectLocator.FileName)).ShouldBeFalse();
    }

    [Fact]
    public void Adopt_RefusesFoldersThatCarryTheNameRatherThanTheInitials()
    {
        AProjectBeforeTheTool();
        Directory.Move(Path.Combine(_root, "Src", "Domain", "AS.Domain"), Path.Combine(_root, "Src", "Domain", "Acme.Shop.Domain"));

        Run(["adopt"], _root).ShouldBe(CleanArchCommand.Failed);

        _error.ToString().ShouldContain("has no Src/Domain/AS.Domain");
        File.Exists(Path.Combine(_root, ProjectLocator.FileName)).ShouldBeFalse();
    }

    private static JsonObject WithoutTheShapesOnlyTheTemplateHolds(string projectFile)
    {
        JsonObject json = JsonNode.Parse(projectFile).ShouldNotBeNull().AsObject();
        json.Remove("client");
        json.Remove("web");
        JsonObject options = json["options"].ShouldNotBeNull().AsObject();
        options.Remove("aspire");
        options.Remove("database");
        return json;
    }

    private void AProjectBeforeTheTool()
    {
        Write("Acme.Shop.sln", string.Empty);
        Write("Tools/Tasks.cs", string.Empty);
        Write("Tools/sonar-scanner.Dockerfile", string.Empty);
        Write(".github/workflows/ci.yml", string.Empty);
        Write("docs/getting-started/overview.md", _overview);
        Directory.CreateDirectory(Path.Combine(_root, "Src", "Domain", "AS.Domain"));
        Directory.CreateDirectory(Path.Combine(_root, "Src", "Application", "AS.Application.Auth"));
        Directory.CreateDirectory(Path.Combine(_root, "Src", "Presentation", "AS.Api"));
        Directory.CreateDirectory(Path.Combine(_root, "Src", "Presentation", "AS.Presentation.Core"));
        Write("Src/Presentation/AS.Worker/Acme.Shop.Worker.csproj", """<Project Sdk="Microsoft.NET.Sdk.Worker"></Project>""");
        Write("Src/Web/package.json", """{ "name": "@acme-shop/web", "private": true }""");
        Write("Src/Web/apps/Site/package.json", """{ "name": "site", "dependencies": { "react": "19.2.0" } }""");
        Write("Src/Web/apps/Site/nginx.conf", string.Empty);
        Write("Src/Web/apps/Site/compose.yml", "      - \"${WEB_SITE_HOST_PORT:-8081}:8080\"");
        Directory.CreateDirectory(Path.Combine(_root, "Src", "Web", "packages", "ui"));
        Directory.CreateDirectory(Path.Combine(_root, "Src", "Web", "packages", "api-client"));
    }

    private void Write(string relative, string content)
    {
        string path = Path.Combine(_root, relative);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, content);
    }

    private int Run(string[] arguments, string workingDirectory) =>
        BuiltInCommands.Run(arguments, workingDirectory, _output, _error, _processes);
}
