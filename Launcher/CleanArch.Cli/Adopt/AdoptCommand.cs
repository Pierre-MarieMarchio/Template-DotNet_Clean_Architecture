using System.CommandLine;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Nodes;
using CleanArch.Tooling.Projects;

namespace CleanArch.Cli.Adopt;

internal static class AdoptCommand
{
    public const string Name = "adopt";

    public const string TemplatePackage = "CleanArch.WebApi.Templates";

    public static readonly CommandRegistration Registration = new(Refusal, Create);

    private static readonly JsonSerializerOptions _written = new()
    {
        WriteIndented = true,
        Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
        NewLine = "\n",
    };

    private static string? Refusal(CommandContext context)
    {
        if (context.Project is { } project)
        {
            return $"This project has its {ProjectLocator.FileName} already, at {project.Root}: {Name} writes it only for a project generated before the tool.";
        }

        return context.RefusedProjectFile is { } refused
            ? $"{refused.Message} {Name} writes {ProjectLocator.FileName} only where none exists: repair this one instead."
            : null;
    }

    private static Command Create(CommandContext context)
    {
        var command = new Command(Name, $"Write {ProjectLocator.FileName} for a project generated before the tool, from what its files hold.");
        Option<bool> dryRun = new("--dry-run") { Description = "Print the file the command would write, and write nothing." };
        Option<string> templateVersion = new("--template-version")
        {
            Description = "The version of the template the project was generated by, where docs/getting-started/overview.md no longer says it.",
        };
        command.Options.Add(dryRun);
        command.Options.Add(templateVersion);
        command.SetAction(parseResult => Run(context, parseResult, dryRun, templateVersion));
        return command;
    }

    private static int Run(CommandContext context, ParseResult parseResult, Option<bool> dryRun, Option<string> templateVersion)
    {
        TextWriter output = parseResult.InvocationConfiguration.Output;
        TextWriter error = parseResult.InvocationConfiguration.Error;
        if (GeneratedProject.Find(context.WorkingDirectory) is not { } project)
        {
            error.WriteLine(
                $"No project around {context.WorkingDirectory}: {Name} looks for the folder that holds one solution beside Tools/Tasks.cs, "
                + "as every project generated before the tool does.");
            return CleanArchCommand.Failed;
        }

        if (!GeneratedProjectFacts.FoldersCarryTheInitials(project))
        {
            error.WriteLine(
                $"{project.Root} has no Src/Domain/{project.FolderOf("Domain")}: its folders carry the product's name rather than its initials, "
                + "and the tool reads the folders by the initials. Rename them first.");
            return CleanArchCommand.Failed;
        }

        TemplateProvenance? provenance = parseResult.GetValue(templateVersion) is { } version
            ? new TemplateProvenance(GeneratedProjectFacts.Provenance(project.Root)?.Package ?? TemplatePackage, version)
            : GeneratedProjectFacts.Provenance(project.Root);
        if (provenance is null)
        {
            error.WriteLine(
                "docs/getting-started/overview.md no longer says which version of the template generated this project: "
                + "give it with --template-version <version>.");
            return CleanArchCommand.Failed;
        }

        string[] unknown = [.. Unknown(project)];
        if (unknown.Length > 0)
        {
            foreach (string fact in unknown)
            {
                error.WriteLine(fact);
            }

            error.WriteLine($"{Name} writes nothing it cannot read from the files: write {ProjectLocator.FileName} by hand, as docs/reference/project-layout.md says.");
            return CleanArchCommand.Failed;
        }

        string json = JsonOf(project, provenance);
        string path = Path.Combine(project.Root, ProjectLocator.FileName);
        if (parseResult.GetValue(dryRun))
        {
            output.WriteLine($"Would write {path}:");
            output.Write(json);
            return CleanArchCommand.Succeeded;
        }

        File.WriteAllText(path, json);
        output.WriteLine($"Wrote {path}:");
        output.Write(json);
        return CleanArchCommand.Succeeded;
    }

    private static IEnumerable<string> Unknown(ProjectFacts project)
    {
        foreach (GeneratedWebApp app in project.HasWorkspace ? GeneratedProjectFacts.WebApps(project.WebFolder) : [])
        {
            if (app.Framework is null)
            {
                yield return $"Src/Web/apps/{app.Name}: its framework cannot be read from its files.";
            }

            if (app.Port is null)
            {
                yield return $"Src/Web/apps/{app.Name}: its compose.yml gives no WEB_<NAME>_HOST_PORT default, so its port cannot be read.";
            }
        }

        foreach (GeneratedPresentation presentation in GeneratedProjectFacts.Presentations(project).Where(presentation => presentation.Framework is null))
        {
            yield return $"Src/Presentation/{project.FolderOf(presentation.Name)}: its framework cannot be read from its project.";
        }
    }

    internal static string JsonOf(ProjectFacts project, TemplateProvenance provenance)
    {
        var file = new JsonObject
        {
            ["template"] = new JsonObject { ["package"] = provenance.Package, ["version"] = provenance.Version },
            ["name"] = project.Name,
            ["options"] = new JsonObject
            {
                ["auth"] = project.Auth,
                ["database"] = project.Database,
                ["examples"] = project.Examples,
                ["files"] = project.Files,
                ["ci"] = project.Ci,
                ["sonar"] = GeneratedProjectFacts.Sonar(project),
                ["agentFiles"] = project.AgentFiles,
                ["aspire"] = GeneratedProjectFacts.Aspire(project),
            },
            ["client"] = project.HasClient,
        };

        if (project.HasWorkspace)
        {
            file["web"] = new JsonObject
            {
                ["scope"] = project.Scope,
                ["apps"] = new JsonArray([.. GeneratedProjectFacts.WebApps(project.WebFolder).Select(app => (JsonNode)new JsonObject
                {
                    ["name"] = app.Name,
                    ["framework"] = app.Framework,
                    ["audience"] = app.Audience,
                    ["rendering"] = app.Rendering,
                    ["port"] = app.Port,
                })]),
                ["packages"] = new JsonArray([.. GeneratedProjectFacts.WebPackages(project.WebFolder).Select(package => (JsonNode)JsonValue.Create(package))]),
            };
        }

        file["presentation"] = new JsonArray([.. GeneratedProjectFacts.Presentations(project).Select(presentation => (JsonNode)new JsonObject
        {
            ["name"] = presentation.Name,
            ["framework"] = presentation.Framework,
        })]);

        return file.ToJsonString(_written) + "\n";
    }
}
