    internal const string GetUseCase = """
        using %P%.Application.Core.Common.Ports;
        using %P%.Application.Core.Common.Results;
        using %P%.Application.Features.%F%.Dtos;
        using %P%.Application.Features.%F%.Errors;
        using %P%.Application.Features.%F%.Ports.%A%Queries;

        namespace %P%.Application.Features.%F%.UseCases.Queries.Get%A%;

        public sealed class Get%A%UseCase(I%A%Queries queries, ICurrentUser currentUser) : IGet%A%UseCase
        {
            public async Task<Result<%A%Dto>> ExecuteAsync(Guid id, CancellationToken cancellationToken = default)
            {
                var userId = currentUser.RequireUserId();

                if (userId.IsFailure)
                {
                    return userId.To<%A%Dto>();
                }

                var found = await queries.GetAsync(userId.Value, id, cancellationToken);

                return found is null
                    ? Result.Failure<%A%Dto>(%A%Errors.%A%NotFound(id))
                    : Result.Success(found);
            }
        }
        """;

    internal const string CreateUseCasePort = """
        using %P%.Application.Core.Common.Results;
