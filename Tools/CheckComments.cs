    private static int Main(string[] args)
    {
        if (args is ["--help"] or ["-h"])
        {
            Console.WriteLine(Help);
            return 0;
        }

        if (Array.IndexOf(args, "--self-test") >= 0)
        {
            return SelfTest();
        }

        return Run(Resolve(args.Length > 0 ? args[0] : "."));
    }

    private static Kind? KindOf(string relative)
    {
        var name = relative[(relative.LastIndexOf('/') + 1)..];

        if (name.EndsWith(".cs", StringComparison.Ordinal))
        {
            return Kind.CSharp;
        }

        if (name.EndsWith(".csproj", StringComparison.Ordinal))
        {
            return Kind.Project;
        }

        if (name.EndsWith(".md", StringComparison.Ordinal))
        {
            return name == "CHANGELOG.md" ? null : Kind.Markdown;
        }

        return SyntaxOf(relative) is null ? null : Kind.Configuration;
    }

    private static Syntax? SyntaxOf(string relative)
    {
        var name = relative[(relative.LastIndexOf('/') + 1)..];

        if (name.StartsWith("appsettings", StringComparison.Ordinal) && name.EndsWith(".json", StringComparison.Ordinal))
        {
            return Syntax.Slash;
        }

        if (Regex.IsMatch(relative, @"(?:^|/)Tests/Load/[^/]+\.js$"))
        {
            return Syntax.Slash;
        }

        if (Regex.IsMatch(relative, @"(?:^|/)Src/Web/(?:.+/)?[^/]+\.(?:ts|tsx|js|mjs|cjs)$")
            && !relative.Contains("/generated/", StringComparison.Ordinal))
        {
            return Syntax.Slash;
        }

        if (Regex.IsMatch(relative, @"(?:^|/)Src/Web/(?:.+/)?(?:compose[^/]*\.ya?ml|nginx\.conf|pnpm-workspace\.yaml)$"))
        {
            return Syntax.Hash;
        }

        if (Regex.IsMatch(name, @"^Directory\..+\.(?:props|targets)$") || name == "coverage.runsettings")
        {
            return Syntax.Xml;
        }

        if (name is ".env.example" or ".editorconfig" or "coverage.minimum" or "Dockerfile"
            || name.EndsWith(".Dockerfile", StringComparison.Ordinal)
            || name.StartsWith("Dockerfile.", StringComparison.Ordinal)
            || Regex.IsMatch(name, @"^docker-compose.*\.ya?ml$")
            || Regex.IsMatch(relative, @"(?:^|/)\.github/workflows/[^/]+\.ya?ml$")
            || Regex.IsMatch(relative, @"(?:^|/)\.github/dependabot\.ya?ml$"))
        {
            return Syntax.Hash;
        }

        return null;
    }

    private static Scan ScanFile(string relative, string text) => KindOf(relative) switch
    {
        Kind.CSharp => new Scan(CSharpFindings(relative, text), 0),
        Kind.Project => new Scan(ProjectFindings(text), 0),
        Kind.Configuration => new Scan(ConfigurationFindings(relative, text), 0),
        Kind.Markdown => MarkdownFindings(text),
        _ => new Scan([], 0),
    };

    private static List<Finding> CSharpFindings(string relative, string text)
    {
        var findings = new List<Finding>();
        var segments = relative.Split('/');

        if (Array.IndexOf(segments, "Migrations", 0, segments.Length - 1) >= 0
            || text.TrimStart('\uFEFF').StartsWith("// <auto-generated", StringComparison.Ordinal))
        {
            return findings;
        }

        var lexer = new CSharpLexer(text);
        lexer.Lex();

        foreach (var (line, banner) in lexer.Banners)
        {
            findings.Add(new Finding(line, 1, "a #region is a section banner", banner));
        }

        var documented = AllowsDocumentation(segments);

        foreach (var comment in lexer.Comments)
        {
            var body = comment.Text.Trim();

            if (body.StartsWith("//#", StringComparison.Ordinal)
                || body.StartsWith("// <auto-generated", StringComparison.Ordinal)
                || body.StartsWith("// </auto-generated", StringComparison.Ordinal))
            {
                continue;
            }

            if (!comment.Documentation)
            {
                findings.Add(new Finding(
                    comment.Line,
                    comment.Lines,
                    body.StartsWith("/*", StringComparison.Ordinal) ? "a block comment" : "a comment",
                    FirstLine(body)));
                continue;
            }

            if (!documented)
            {
                findings.Add(new Finding(
                    comment.Line, 1, "XML documentation outside an API controller or contract", body));
                continue;
            }

            var element = XmlElement.Matches(body)
                .Select(match => match.Groups[1].Value)
                .FirstOrDefault(name => !DocumentationElements.Contains(name));

            if (element is not null)
            {
                findings.Add(new Finding(
                    comment.Line, 1, $"<{element}> is not an element the API documentation uses", body));
                continue;
            }

            if (Narrative(body) is { } pattern)
            {
                findings.Add(new Finding(comment.Line, 1, $"narrates history, /{pattern}/", body));
            }
        }

        return [.. findings.OrderBy(finding => finding.Line)];
    }

    private static bool AllowsDocumentation(string[] segments)
    {
        var api = Array.FindIndex(segments, segment => segment.EndsWith(".Api", StringComparison.Ordinal));

        if (api < 0 || api >= segments.Length - 1)
        {
            return false;
        }

        var folders = segments[(api + 1)..^1];

        if (folders.Length > 0 && folders[^1] == "Controllers")
        {
            return true;
        }

        var contracts = Array.IndexOf(folders, "Contracts");

        return contracts >= 0 && Array.IndexOf(folders, "Mapping", contracts + 1) < 0;
    }

    private static List<Finding> ProjectFindings(string text)
    {
        var findings = new List<Finding>();
        var lines = SplitLines(text);
        var open = -1;
        var start = 0;

        for (var index = 0; index < lines.Count; index++)
        {
            var line = lines[index];
            var cursor = 0;

            while (cursor < line.Length)
            {
                if (open < 0)
                {
                    var at = line.IndexOf("<!--", cursor, StringComparison.Ordinal);

                    if (at < 0)
                    {
                        break;
                    }

                    open = index;
                    start = at;
                    cursor = at + 4;
                }

                var close = line.IndexOf("-->", cursor, StringComparison.Ordinal);

                if (close < 0)
                {
                    break;
                }

                var opening = lines[open][start..];

                if (!opening.StartsWith("<!--#", StringComparison.Ordinal))
                {
                    findings.Add(new Finding(open + 1, index - open + 1, "a comment in a project file", FirstLine(opening).Trim()));
                }

                open = -1;
                cursor = close + 3;
            }
        }

        return findings;
    }

    private static List<Finding> ConfigurationFindings(string relative, string text)
    {
        var findings = new List<Finding>();
        var lines = SplitLines(text);
        var roles = Roles(relative, lines);
        var first = -1;
        var count = 0;

        void Flush()
        {
            if (count > 1)
            {
                findings.Add(new Finding(
                    first + 1,
                    count,
                    $"{count} comment lines in a row: one guidance line per setting",
                    lines[first].Trim().TrimStart('\uFEFF')));
            }

            first = -1;
            count = 0;
        }

        for (var index = 0; index < lines.Count; index++)
        {
            switch (roles[index])
            {
                case LineRole.Comment:
                    if (count == 0)
                    {
                        first = index;
                    }

                    count++;

                    if (Narrative(lines[index]) is { } pattern)
                    {
                        findings.Add(new Finding(index + 1, 1, $"narrates history, /{pattern}/", lines[index].Trim()));
                    }

                    break;
                case LineRole.Blank:
                    break;
                default:
                    Flush();
                    break;
            }
        }

        Flush();

        return [.. findings.OrderBy(finding => finding.Line)];
    }

    private static LineRole[] Roles(string relative, List<string> lines)
    {
        var syntax = SyntaxOf(relative) ?? Syntax.Hash;
        var name = relative[(relative.LastIndexOf('/') + 1)..];
        var dockerfile = name == "Dockerfile" || name.EndsWith(".Dockerfile", StringComparison.Ordinal)
                         || name.StartsWith("Dockerfile.", StringComparison.Ordinal);
        var editorconfig = name == ".editorconfig";
        var roles = new LineRole[lines.Count];
        var contentSeen = false;
        var inComment = false;
        var inMarker = false;

        for (var index = 0; index < lines.Count; index++)
        {
            var line = lines[index].Trim().TrimStart('\uFEFF').Trim();

            roles[index] = syntax switch
            {
                Syntax.Hash => HashRole(line),
                Syntax.Slash => SlashRole(line),
                _ => XmlRole(line),
            };

            if (roles[index] == LineRole.Content)
            {
                contentSeen = true;
            }
        }

        return roles;

        LineRole HashRole(string line)
        {
            if (line.Length == 0)
            {
                return LineRole.Blank;
            }

            if (line.StartsWith('#'))
            {
                if (HashMarker.IsMatch(line))
                {
                    return LineRole.Marker;
                }

                return dockerfile && !contentSeen && DockerParserDirective.IsMatch(line)
                    ? LineRole.Content
                    : LineRole.Comment;
            }

            return editorconfig && line.StartsWith(';') ? LineRole.Comment : LineRole.Content;
        }

        LineRole SlashRole(string line)
        {
            if (inComment)
            {
                inComment = !line.Contains("*/", StringComparison.Ordinal);
                return LineRole.Comment;
            }

            if (line.Length == 0)
            {
                return LineRole.Blank;
            }

            if (line.StartsWith("//#", StringComparison.Ordinal) || line.StartsWith("/*#", StringComparison.Ordinal))
            {
                return LineRole.Marker;
            }

            if (line.StartsWith("//", StringComparison.Ordinal))
            {
                return LineRole.Comment;
            }

            if (line.StartsWith("/*", StringComparison.Ordinal))
            {
                inComment = !line[2..].Contains("*/", StringComparison.Ordinal);
                return LineRole.Comment;
            }

            return LineRole.Content;
        }

        LineRole XmlRole(string line)
        {
            if (inComment)
            {
                inComment = !line.Contains("-->", StringComparison.Ordinal);
                return LineRole.Comment;
            }

            if (inMarker)
            {
                inMarker = !line.Contains("-->", StringComparison.Ordinal);
                return inMarker ? LineRole.Content : LineRole.Marker;
            }

            if (line.Length == 0)
            {
                return LineRole.Blank;
            }

            if (line.StartsWith("<!--#", StringComparison.Ordinal))
            {
                inMarker = !line.Contains("-->", StringComparison.Ordinal);
                return LineRole.Marker;
            }

            if (line.StartsWith("<!--", StringComparison.Ordinal))
            {
                inComment = !line[4..].Contains("-->", StringComparison.Ordinal);
                return LineRole.Comment;
            }

            return LineRole.Content;
        }
    }

    private static Scan MarkdownFindings(string text)
    {
        var findings = new List<Finding>();
        var exemptions = 0;
        var exempt = false;
        var number = 0;

        foreach (var line in SplitLines(text))
        {
            number++;

            if (line.Trim().Length == 0)
            {
                exempt = false;
            }
            else if (NarrativeMarker.IsMatch(line))
            {
                exempt = true;
            }

            if (Narrative(line) is not { } pattern)
            {
                continue;
            }

            if (exempt)
            {
                exemptions++;
            }
            else
            {
                findings.Add(new Finding(number, 1, $"narrates history, /{pattern}/", line.Trim()));
            }
        }

        return new Scan(findings, exemptions);
    }

    private static string? Narrative(string line) =>
        NarrativeRules.FirstOrDefault(rule => rule.IsMatch(line))?.ToString();

    private sealed class CSharpLexer(string text)
    {
        private readonly int[] _lineStarts = LineStarts(text);
        private int _position;
        private bool _inRegion;

        internal List<Comment> Comments { get; } = [];

        internal List<(int Line, string Text)> Banners { get; } = [];

        internal void Lex() => Code(insideHole: false);

        private char At(int offset) =>
            _position + offset < text.Length ? text[_position + offset] : '\0';

        private int LineOf(int index)
        {
            var found = Array.BinarySearch(_lineStarts, index);

            return (found >= 0 ? found : ~found - 1) + 1;
        }

        private int EndOfLine(int from)
        {
            var end = text.IndexOf('\n', from);

            return end < 0 ? text.Length : end;
        }

        private bool AtLineStart()
        {
            for (var index = _position - 1; index >= 0 && text[index] != '\n'; index--)
            {
                if (!char.IsWhiteSpace(text[index]) && text[index] != '\uFEFF')
                {
                    return false;
                }
            }

            return true;
        }

        private bool StringAhead()
        {
            var index = _position;

            while (index < text.Length && text[index] is '$' or '@')
            {
                index++;
            }

            return index < text.Length && text[index] == '"';
        }

        private void Code(bool insideHole)
        {
            var depth = 0;

            while (_position < text.Length)
            {
                var current = text[_position];

                if (current == '/' && At(1) == '/')
                {
                    LineComment();
                }
                else if (current == '/' && At(1) == '*')
                {
                    BlockComment();
                }
                else if (_inRegion && current == '*' && At(1) == '/')
                {
                    _inRegion = false;
                    _position += 2;
                }
                else if (current == '#' && AtLineStart())
                {
                    Directive();
                }
                else if (current is '"' or '$' or '@' && StringAhead())
                {
                    StringLiteral();
                }
                else if (current == '\'')
                {
                    CharLiteral();
                }
                else
                {
                    if (insideHole && current == '{')
                    {
                        depth++;
                    }
                    else if (insideHole && current == '}')
                    {
                        if (depth == 0)
                        {
                            return;
                        }

                        depth--;
                    }

                    _position++;
                }
            }
        }

        private void LineComment()
        {
            var end = EndOfLine(_position);
            var body = text[_position..end].TrimEnd('\r');
            var documentation = body.StartsWith("///", StringComparison.Ordinal)
                                && !body.StartsWith("////", StringComparison.Ordinal);

            Comments.Add(new Comment(LineOf(_position), 1, body, documentation));
            _position = end;
        }

        private void BlockComment()
        {
            var close = text.IndexOf("*/", _position + 2, StringComparison.Ordinal);
            var end = close < 0 ? text.Length : close + 2;

            if (At(2) == '#')
            {
                var lineEnd = EndOfLine(_position);

                if (close >= 0 && close < lineEnd)
                {
                    _position = end;
                    return;
                }

                _inRegion = true;
                _position = lineEnd;
                return;
            }

            var first = LineOf(_position);
            var last = LineOf(Math.Max(_position, end - 1));

            Comments.Add(new Comment(first, last - first + 1, text[_position..end], Documentation: false));
            _position = end;
        }

        private void Directive()
        {
            var end = EndOfLine(_position);
            var line = text[_position..end].TrimEnd('\r');
            var keyword = new string([.. line.Skip(1).TakeWhile(char.IsLetter)]);

            if (_inRegion && keyword is "if" or "elseif" or "else" or "endif")
            {
                if (line.Contains("*/", StringComparison.Ordinal))
                {
                    _inRegion = false;
                }

                _position = end;
                return;
            }

            if (keyword is "region" or "endregion")
            {
                Banners.Add((LineOf(_position), line.Trim()));
            }
            else if (!line.StartsWith("#!", StringComparison.Ordinal) && !line.StartsWith("#:", StringComparison.Ordinal))
            {
                var comment = line.IndexOf("//", StringComparison.Ordinal);

                if (comment >= 0)
                {
                    Comments.Add(new Comment(LineOf(_position), 1, line[comment..], Documentation: false));
                }
            }

            _position = end;
        }

        private void StringLiteral()
        {
            var dollars = 0;
            var verbatim = false;

            while (text[_position] is '$' or '@')
            {
                if (text[_position] == '$')
                {
                    dollars++;
                }
                else
                {
                    verbatim = true;
                }

                _position++;
            }

            var quotes = 0;

            while (At(quotes) == '"')
            {
                quotes++;
            }

            if (!verbatim && quotes >= 3)
            {
                RawString(quotes, dollars);
                return;
            }

            _position++;

            while (_position < text.Length)
            {
                var current = text[_position];

                if (verbatim && current == '"' && At(1) == '"')
                {
                    _position += 2;
                }
                else if (current == '"')
                {
                    _position++;
                    return;
                }
                else if (!verbatim && current == '\\')
                {
                    _position += 2;
                }
                else if (!verbatim && current == '\n')
                {
                    return;
                }
                else if (dollars > 0 && current == '{' && At(1) == '{')
                {
                    _position += 2;
                }
                else if (dollars > 0 && current == '{')
                {
                    _position++;
                    Code(insideHole: true);
                    _position++;
                }
                else
                {
                    _position++;
                }
            }
        }

        private void RawString(int quotes, int dollars)
        {
            _position += quotes;

            while (_position < text.Length)
            {
                var current = text[_position];

                if (current == '"' && string.CompareOrdinal(text, _position, new string('"', quotes), 0, quotes) == 0)
                {
                    _position += quotes;
                    return;
                }

                if (dollars > 0 && current == '{')
                {
                    var run = 0;

                    while (At(run) == '{')
                    {
                        run++;
                    }

                    _position += run;

                    if (run >= dollars)
                    {
                        Code(insideHole: true);

                        for (var closed = 0; closed < dollars && At(0) == '}'; closed++)
                        {
                            _position++;
                        }
                    }

                    continue;
                }

                _position++;
            }
        }

        private void CharLiteral()
        {
            _position += At(1) == '\\' ? 3 : 2;

            while (_position < text.Length && text[_position] != '\'' && text[_position] != '\n')
            {
                _position++;
            }

            _position++;
        }

        private static int[] LineStarts(string text)
        {
            var starts = new List<int> { 0 };

            for (var index = 0; index < text.Length; index++)
            {
                if (text[index] == '\n')
                {
                    starts.Add(index + 1);
                }
            }

            return [.. starts];
        }
    }

    private static int Run(string root)
    {
        var files = CollectFiles(root);
        var problems = new List<(string Path, Finding Finding)>();
        var exemptions = 0;

        foreach (var path in files)
        {
            var relative = Relative(root, path);
            var scan = ScanFile(relative, ReadText(path));

            exemptions += scan.Exemptions;
            problems.AddRange(scan.Findings.Select(finding => (relative, finding)));
        }

        var kinds = files
            .GroupBy(path => KindOf(Relative(root, path)))
            .ToDictionary(group => group.Key!.Value, group => group.Count());

        Console.WriteLine(
            $"Scanned {files.Count} file(s): {kinds.GetValueOrDefault(Kind.CSharp)} C#, "
            + $"{kinds.GetValueOrDefault(Kind.Project)} project, {kinds.GetValueOrDefault(Kind.Configuration)} configuration, "
            + $"{kinds.GetValueOrDefault(Kind.Markdown)} Markdown; honoured {exemptions} narrative-ok marker(s).");
        Console.WriteLine();

        if (files.Count == 0)
        {
            Console.WriteLine("PROBLEM: no file was examined, so this check proves nothing.");
            return 1;
        }

        if (problems.Count == 0)
        {
            Console.WriteLine("No comment outside the allowlist.");
            return 0;
        }

        Console.WriteLine($"PROBLEMS ({problems.Count}):");
        Console.WriteLine("  Code reads by itself: a decision goes to an ADR in docs/decisions/, a name that needs a comment is renamed.");
        Console.WriteLine("  `dotnet run Tools/CheckComments.cs -- --help` states what is allowed where.");
        Console.WriteLine();

        foreach (var (path, finding) in problems)
        {
            Console.WriteLine($"  ! {path}:{finding.Line}  {finding.Rule}");
            Console.WriteLine($"      {Truncate(finding.Text, 160)}");
        }

        Console.WriteLine();
        Console.WriteLine("By area:");

        foreach (var area in problems
                     .GroupBy(problem => problem.Path.Contains('/', StringComparison.Ordinal) ? problem.Path[..problem.Path.IndexOf('/', StringComparison.Ordinal)] : "(root)")
                     .OrderBy(group => group.Key, StringComparer.Ordinal))
        {
            Console.WriteLine(
                $"  {area.Key,-20} {area.Count(),6} finding(s) {area.Sum(problem => problem.Finding.Lines),7} line(s)");
        }

        return 1;
    }

    private static List<string> CollectFiles(string root)
    {
        var collected = new List<string>();

        Walk(new DirectoryInfo(root), collected);

        var candidates = collected
            .Where(path => KindOf(Relative(root, path)) is not null)
            .Order(StringComparer.Ordinal)
            .ToList();

        var ignored = GitIgnored(root, candidates);

        return [.. candidates.Where(path => !ignored.Contains(path))];
    }

    private static void Walk(DirectoryInfo directory, List<string> collected)
    {
        FileSystemInfo[] entries;

        try
        {
            entries = directory.GetFileSystemInfos();
        }
        catch (Exception exception) when (exception is IOException or UnauthorizedAccessException)
        {
            return;
        }

        foreach (var entry in entries)
        {
            if (entry is DirectoryInfo subdirectory)
            {
                if (entry.LinkTarget is null && !SkippedDirectoryNames.Contains(entry.Name))
                {
                    Walk(subdirectory, collected);
                }
            }
            else if (entry.Exists)
            {
                collected.Add(entry.FullName);
            }
        }
    }

    private static HashSet<string> GitIgnored(string root, List<string> paths)
    {
        var ignored = new HashSet<string>(StringComparer.Ordinal);

        if (paths.Count == 0)
        {
            return ignored;
        }

        try
        {
            var startInfo = new ProcessStartInfo("git")
            {
                WorkingDirectory = root,
                RedirectStandardInput = true,
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false,
                StandardInputEncoding = new UTF8Encoding(false),
            };

            startInfo.ArgumentList.Add("check-ignore");
            startInfo.ArgumentList.Add("--stdin");

            using var process = Process.Start(startInfo);

            if (process is null)
            {
                return ignored;
            }

            var standardOutput = process.StandardOutput.ReadToEndAsync();
            var standardError = process.StandardError.ReadToEndAsync();

            process.StandardInput.Write(string.Join("\n", paths));
            process.StandardInput.Close();
            process.WaitForExit();

            standardError.GetAwaiter().GetResult();

            foreach (var line in standardOutput.GetAwaiter().GetResult()
                         .Split('\n', StringSplitOptions.RemoveEmptyEntries))
            {
                ignored.Add(line.TrimEnd('\r'));
            }
        }
        catch (Exception exception) when (exception is not OutOfMemoryException)
        {
            return [];
        }

        return ignored;
    }

